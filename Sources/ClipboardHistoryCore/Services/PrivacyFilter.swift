import AppKit
import Foundation

public struct PasteboardSourceApplication {
    let bundleIdentifier: String?
    let localizedName: String?

    public init(bundleIdentifier: String?, localizedName: String?) {
        self.bundleIdentifier = bundleIdentifier
        self.localizedName = localizedName
    }

    init(_ runningApplication: NSRunningApplication?) {
        self.bundleIdentifier = runningApplication?.bundleIdentifier
        self.localizedName = runningApplication?.localizedName
    }
}

enum PrivacyFilter {
    private static let concealedType = "org.nspasteboard.concealedtype"
    private static let metadataTypes: Set<String> = [
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype"
    ]
    private static let onePasswordFragments = ["1password", "onepassword", "agilebits"]

    static func shouldSkip(items: [NSPasteboardItem], sourceApplication: PasteboardSourceApplication?) -> Bool {
        isOnePasswordSource(sourceApplication) || items.contains { item in
            item.types.contains { isPrivateMarkerType($0.rawValue) }
        }
    }

    static func isMarkerType(_ typeIdentifier: String) -> Bool {
        // Generated/transient metadata is not proof of a secret. Capture the content,
        // but don't restore these bookkeeping markers with the archived formats.
        metadataTypes.contains(typeIdentifier.lowercased()) || isPrivateMarkerType(typeIdentifier)
    }

    private static func isPrivateMarkerType(_ typeIdentifier: String) -> Bool {
        let normalized = typeIdentifier.lowercased()
        return normalized == concealedType || onePasswordFragments.contains { normalized.contains($0) }
    }

    private static func isOnePasswordSource(_ app: PasteboardSourceApplication?) -> Bool {
        guard let app else {
            return false
        }
        let bundleID = app.bundleIdentifier?.lowercased() ?? ""
        let name = app.localizedName?.lowercased() ?? ""
        return onePasswordFragments.contains { fragment in
            bundleID.contains(fragment) || name.contains(fragment)
        }
    }
}
